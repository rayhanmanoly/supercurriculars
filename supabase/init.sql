-- ============================================================
-- supabase/init.sql
-- Standalone bootstrap for a fresh Supabase project.
-- Combines schema, security fixes, ambassador RPCs, and demo seed.
-- Does NOT include production PII / OAuth dumps.
--
-- Usage (SQL editor or psql Session mode, port 5432):
--   psql "postgres://postgres:<password>@db.<ref>.supabase.co:5432/postgres" \
--     -f supabase/init.sql
--
-- After running:
--   1. Enable Google OAuth in Supabase Auth
--   2. Copy .env.example → .env.local with project URL + anon key
--   3. First login creates a profile via /login/onboarding
--   4. To test teacher features: UPDATE profiles SET role = 'teacher' WHERE id = '<uuid>';
-- ============================================================

