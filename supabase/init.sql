-- -------------------------------------------------------
-- Privilege escalation guard (profiles)
-- Blocks authenticated clients from changing role / can_add /
-- can_add_approver. SECURITY DEFINER RPCs run as function owner
-- (postgres), so current_user is not 'authenticated' and they pass.
-- INSERT (onboarding) is allowed to set initial role.
-- -------------------------------------------------------

CREATE OR REPLACE FUNCTION public.prevent_privilege_escalation()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF TG_OP = 'UPDATE'
     AND current_user IN ('authenticated', 'anon')
     AND (
       NEW.role IS DISTINCT FROM OLD.role
       OR NEW.can_add IS DISTINCT FROM OLD.can_add
       OR NEW.can_add_approver IS DISTINCT FROM OLD.can_add_approver
     ) THEN
    RAISE EXCEPTION 'Cannot modify privileged profile fields';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_prevent_privilege_escalation ON public.profiles;
CREATE TRIGGER trg_prevent_privilege_escalation
  BEFORE UPDATE ON public.profiles
  FOR EACH ROW
  EXECUTE PROCEDURE public.prevent_privilege_escalation();

-- Keep profile_tokens.updated_at fresh
CREATE OR REPLACE FUNCTION public.touch_profile_tokens_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_touch_profile_tokens_updated_at ON public.profile_tokens;
CREATE TRIGGER trg_touch_profile_tokens_updated_at
  BEFORE UPDATE ON public.profile_tokens
  FOR EACH ROW
  EXECUTE PROCEDURE public.touch_profile_tokens_updated_at();


-- -------------------------------------------------------
-- Ambassador RPCs (teachers grant/revoke can_add)
-- -------------------------------------------------------

CREATE OR REPLACE FUNCTION public.grant_can_add(target_student_id uuid)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  caller_role text;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'Not authenticated';
  END IF;

  SELECT role INTO caller_role FROM public.profiles WHERE id = auth.uid();
  IF caller_role IS DISTINCT FROM 'teacher' THEN
    RAISE EXCEPTION 'Only teachers can grant contributor access';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM public.profiles
    WHERE id = target_student_id AND role = 'student'
  ) THEN
    RAISE EXCEPTION 'Target must be a student profile';
  END IF;

  UPDATE public.profiles
  SET can_add = true,
      can_add_approver = auth.uid()
  WHERE id = target_student_id
    AND role = 'student';
END;
$$;

CREATE OR REPLACE FUNCTION public.revoke_can_add(target_student_id uuid)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  caller_role text;
  rows_updated int;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'Not authenticated';
  END IF;

  SELECT role INTO caller_role FROM public.profiles WHERE id = auth.uid();
  IF caller_role IS DISTINCT FROM 'teacher' THEN
    RAISE EXCEPTION 'Only teachers can revoke contributor access';
  END IF;

  UPDATE public.profiles
  SET can_add = false,
      can_add_approver = NULL
  WHERE id = target_student_id
    AND role = 'student'
    AND can_add_approver = auth.uid();

  GET DIAGNOSTICS rows_updated = ROW_COUNT;
  IF rows_updated = 0 THEN
    RAISE EXCEPTION 'No ambassador found that you approved, or already revoked';
  END IF;
END;
$$;

REVOKE ALL ON FUNCTION public.grant_can_add(uuid) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.revoke_can_add(uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.grant_can_add(uuid) TO authenticated;
GRANT EXECUTE ON FUNCTION public.revoke_can_add(uuid) TO authenticated;


